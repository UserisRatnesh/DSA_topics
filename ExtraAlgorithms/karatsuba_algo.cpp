// TOPIC: Karatsuba Multiplication
// TC: O(n^1.59) n=No of digits, b=base(10 for Decimal number)
ll getLength(ll X) {
  if (X == 0)
    return 1;
  ll len = 0;
  while (X > 0) {
    len++;
    X /= 10;
  }
  return len;
}

// Integer power of 10 (avoids floating pow bug)
ll powerBase(ll n) {
  ll res = 1;
  ll base = 10;
  while (n--) {
    res *= base;
  }
  return res;
}

ll karatsuba(ll X, ll Y) {
  if (X < 10 && Y < 10) {
    return X * Y;
  }

  ll maxLen = max(getLength(X), getLength(Y));
  ll halfLen = (maxLen + 1) / 2;

  ll multiplier = powerBase(halfLen);

  ll a = X / multiplier;
  ll b = X % multiplier;
  ll c = Y / multiplier;
  ll d = Y % multiplier;

  ll s1 = karatsuba(a, c);
  ll s2 = karatsuba(b, d);
  ll s3 = karatsuba(a + b, c + d);

  ll s4 = s3 - s1 - s2;

  return s1 * powerBase(2 * halfLen) + s4 * multiplier + s2;
}

